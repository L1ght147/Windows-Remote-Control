def is_supported_language(value: str) -> bool:
    return value in SUPPORTED_LANGUAGES


def t(language: Language, key: str, **values: object) -> str:
    return MESSAGES[language][key].format(**values)


class LocalizedError(RuntimeError):
    """An error whose message is shown to the user in their language."""

    def __init__(self, key: str, **values: object) -> None:
        self.key = key
        self.values = values
        super().__init__(t("en", key, **values))

    def localized(self, language: Language) -> str:
        return t(language, self.key, **self.values)
